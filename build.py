#!/usr/bin/env python3
"""Assemble guest/mh.asm and write guestcode.py (binary + symbol offsets).

NASM is taken from the MH_NASM environment variable (a command line, e.g.
"wsl -d Debian -- nasm") or from PATH.
"""
import base64
import os
import pathlib
import re
import shlex
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
GUEST = HERE / "guest"


def nasm_command():
    env = os.environ.get("MH_NASM")
    if env:
        return shlex.split(env, posix=False)
    exe = shutil.which("nasm")
    if exe:
        return [exe]
    sys.exit("nasm not found: put it on PATH or set MH_NASM")


def main():
    cmd = nasm_command()
    wsl = cmd and pathlib.Path(cmd[0]).stem.lower() == "wsl"
    if wsl:
        # run inside the guest directory so relative names work in WSL too
        cmd = cmd[:1] + ["--cd", str(GUEST)] + cmd[1:]
    subprocess.run(cmd + ["-f", "bin", "-o", "mh.bin", "mh.asm"],
                   cwd=GUEST, check=True)
    blob = (GUEST / "mh.bin").read_bytes()
    symbols = {}
    for line in (GUEST / "mh.map").read_text().splitlines():
        m = re.match(r"\s*([0-9A-Fa-f]+)\s+([0-9A-Fa-f]+)\s+([A-Za-z_]\w*)$", line)
        if m:
            symbols[m.group(3)] = int(m.group(2), 16)
    lines = [
        '"""Generated by build.py from guest/mh.asm - do not edit."""',
        "import base64",
        "",
        "BLOB = base64.b64decode(",
    ]
    text = base64.b64encode(blob).decode()
    for i in range(0, len(text), 76):
        lines.append(f'    "{text[i:i + 76]}"')
    lines.append(")")
    lines.append("")
    lines.append("SYMBOLS = {")
    for name in sorted(symbols, key=lambda n: (symbols[n], n)):
        lines.append(f'    "{name}": 0x{symbols[name]:04X},')
    lines.append("}")
    lines.append("")
    (HERE / "guestcode.py").write_text("\n".join(lines), newline="\n")
    print(f"guestcode.py: {len(blob)} bytes, {len(symbols)} symbols")


if __name__ == "__main__":
    main()
